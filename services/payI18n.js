/** pay('cardNumber', 'tr') → "Kart Numarası" */
function pay(key, locale, vars) {
  const code = i18n.normalizeLocale(locale);
  const dict = PAY[code] || PAY.en;
  let out = dict[key] != null ? dict[key] : (PAY.en[key] != null ? PAY.en[key] : key);
  if (vars) {
    Object.keys(vars).forEach((k) => {
      out = String(out).split(`{{${k}}}`).join(vars[k]);
    });
  }
  return out;
}

/** Bütün lüğəti bir dil üçün qaytarır (EJS / JSON üçün) */
function payDict(locale) {
  const code = i18n.normalizeLocale(locale);
  return Object.assign({}, PAY.en, PAY[code] || {});
}

/** Aktiv dilə uyğun bank qrupunun başlığı */
function bankGroupTitle(locale) {
  const code = i18n.normalizeLocale(locale);
  const map = { az: 'azBanks', ru: 'ruBanks', tr: 'trBanks', ka: 'geBanks', en: 'cryptoWallets' };
  return pay(map[code] || 'selectCardType', code);
}

